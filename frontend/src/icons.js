// SVG Status Symbol Badge (Color-independent shapes replacing emoji)
export const StatusSymbol = ({ status, size = 12, fill = 'currentColor', className = '', ...props }) => {
  switch (status) {
    case 'safe':
      // Solid Circle
      return (
        <svg width={size} height={size} viewBox="0 0 16 16" className={className} {...props} aria-hidden="true">
          <circle cx="8" cy="8" r="6" fill={fill} />
        </svg>
      );
    case 'semi_critical':
      // Solid Triangle pointing up
      return (
        <svg width={size} height={size} viewBox="0 0 16 16" className={className} {...props} aria-hidden="true">
          <polygon points="8 2 14 14 2 14" fill={fill} />
        </svg>
      );
    case 'critical':
      // Solid Square
      return (
        <svg width={size} height={size} viewBox="0 0 16 16" className={className} {...props} aria-hidden="true">
          <rect x="2.5" y="2.5" width="11" height="11" rx="1.5" fill={fill} />
        </svg>
      );
    case 'over_exploited':
      // Rotated Diamond with inner stroke
      return (
        <svg width={size} height={size} viewBox="0 0 16 16" className={className} {...props} aria-hidden="true">
          <polygon points="8 1.5 14.5 8 8 14.5 1.5 8" fill={fill} />
        </svg>
      );
    default:
      // Dash / Line for pending or unknown
      return (
        <svg width={size} height={size} viewBox="0 0 16 16" className={className} {...props} aria-hidden="true">
          <rect x="2" y="7" width="12" height="2.5" rx="1" fill={fill} />
        </svg>
      );
  }
};
